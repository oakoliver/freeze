// style registered in github.com/alecthomas/chroma/v2/styles, plus freeze's
// "charm" style, as raw entry strings. Run from the repository root:
//
//	(cd scripts/gen-chroma && go run .) > src/chroma-data.ts
//	(cd scripts/gen-chroma && go run . lexers) > src/lexers-data.ts
