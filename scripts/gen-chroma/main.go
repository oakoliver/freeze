type xmlStyle struct {
	Name    string `xml:"name,attr"`
	Entries []struct {
		Type  string `xml:"type,attr"`
		Style string `xml:"style,attr"`
	} `xml:"entry"`
}

type lexerInfo struct {
	Name           string   `json:"name"`
	Aliases        []string `json:"aliases,omitempty"`
	Filenames      []string `json:"filenames,omitempty"`
	AliasFilenames []string `json:"aliasFilenames,omitempty"`
	Priority       float32  `json:"priority,omitempty"`
	AnalyseFirst   bool     `json:"analyseFirst,omitempty"`
	Analyse        []struct {
		Pattern string  `json:"pattern"`
		Score   float32 `json:"score"`
	} `json:"analyse,omitempty"`
}

func main() {
	if len(os.Args) > 1 && os.Args[1] == "lexers" {
		var out []lexerInfo
		for _, l := range lexers.GlobalLexerRegistry.Lexers {
			c := l.Config()
			li := lexerInfo{Name: c.Name, Aliases: c.Aliases, Filenames: c.Filenames, AliasFilenames: c.AliasFilenames, Priority: c.Priority}
			if c.Analyse != nil {
				li.AnalyseFirst = c.Analyse.First
				for _, r := range c.Analyse.Regexes {
					li.Analyse = append(li.Analyse, struct {
						Pattern string  `json:"pattern"`
						Score   float32 `json:"score"`
					}{r.Pattern, r.Score})
				}
			}
			out = append(out, li)
		}
		fmt.Println("// Generated by scripts/gen-chroma from github.com/alecthomas/chroma/v2 v2.24.1 (MIT,")
		fmt.Println("// Copyright (C) 2017 Alec Thomas): the lexer registry, in registration order. Do not edit.")
		fmt.Println()
		fmt.Println("export interface LexerConfig {\n  name: string;\n  aliases?: string[];\n  filenames?: string[];\n  aliasFilenames?: string[];\n  priority?: number;\n  analyseFirst?: boolean;\n  analyse?: Array<{ pattern: string; score: number }>;\n}")
		fmt.Println()
		fmt.Println("export const LEXERS: LexerConfig[] = [")
		for _, li := range out {
			b, _ := json.Marshal(li)
			fmt.Printf("  %s,\n", b)
		}
		fmt.Println("];")
		return
	}
	types := map[string]int{}
	for t := range chroma.StandardTypes {
		types[t.String()] = int(t)
	}
	names := styles.Names()
	out := map[string]map[string]string{}
	for _, n := range names {
		var buf bytes.Buffer
		if err := xml.NewEncoder(&buf).Encode(styles.Registry[n]); err != nil {
			panic(err)
		}
		var s xmlStyle
		if err := xml.Unmarshal(buf.Bytes(), &s); err != nil {
			panic(err)
		}
		entries := map[string]string{}
		for _, e := range s.Entries {
			entries[e.Type] = e.Style
		}
		out[n] = entries
	}
	tj, _ := json.Marshal(sortedMap(types))
	fmt.Println("// Generated by scripts/gen-chroma from github.com/alecthomas/chroma/v2 v2.24.1 (MIT,")
	fmt.Println("// Copyright (C) 2017 Alec Thomas) and charmbracelet/freeze's charm style. Do not edit.")
	fmt.Println()
	fmt.Printf("/** chroma.StandardTypes: token type name to numeric value. */\nexport const TOKEN_TYPES: Record<string, number> = %s;\n\n", tj)
	fmt.Println("/** Raw style entries (Pygments syntax) of every registered chroma style, by lower-case name. */")
	fmt.Println("export const STYLES: Record<string, Record<string, string>> = {")
	for _, n := range names {
		ej, _ := json.Marshal(out[n])
		fmt.Printf("  %q: %s,\n", n, ej)
	}
	fmt.Println("};")
	_ = os.Stdout.Sync()
}

func sortedMap(m map[string]int) json.RawMessage {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return m[keys[i]] < m[keys[j]] })
	var b bytes.Buffer
	b.WriteString("{")
	for i, k := range keys {
		if i > 0 {
			b.WriteString(",")
		}
		fmt.Fprintf(&b, "%q:%d", k, m[k])
	}
	b.WriteString("}")
	return b.Bytes()
}
